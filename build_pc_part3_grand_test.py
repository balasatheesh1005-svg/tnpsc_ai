def main():
    qs = generate_grand_test_questions()
    print(f"Generated {len(qs)} Grand Test questions.")

    # 1. Collision check against Core questions (325 questions)
    core_files = [
        "data/questions/polity/parliamentary_committees_easy.json",
        "data/questions/polity/parliamentary_committees_medium.json",
        "data/questions/polity/parliamentary_committees_hard.json",
        "data/questions/polity/parliamentary_committees_statement_based.json",
        "data/questions/polity/parliamentary_committees_pyq.json",
        "data/questions/polity/parliamentary_committees_reasoning.json",
        "data/questions/polity/parliamentary_committees_match_the_following.json",
        "data/questions/polity/parliamentary_committees_chronology.json"
    ]
    dup_index = TopicDuplicateIndex("parliamentary_committees")
    loaded = dup_index.load_from_files(core_files)
    print(f"Loaded {loaded} Core questions into Duplicate Index.")

    collisions = []
    for q in qs:
        is_dup, reason = dup_index.check_duplicate(q["question_en"], q["question_ta"])
        if is_dup:
            collisions.append((q["id"], reason))

    if collisions:
        print(f"FAIL: Found {len(collisions)} duplicate collisions with Core questions:")
        for cid, reason in collisions[:10]:
            print(f"  - {cid}: {reason}")
        raise ValueError("Collision check failed!")
    else:
        print("PASS: 0 collisions detected against Core (325 questions).")

    # 2. Randomize and balance dataset (exact 25 A, 25 B, 25 C, 25 D)
    balanced_qs = randomize_and_balance_dataset(qs, seed=2033)
    keys = [q["correct_answer"] for q in balanced_qs]
    key_counts = Counter(keys)
    print("Grand Test Balanced Key counts:", key_counts)
    assert key_counts == {"A": 25, "B": 25, "C": 25, "D": 25}, f"Unbalanced Grand Test keys: {key_counts}"

    # 3. Content Validation
    validator = ContentValidator()
    all_errors = []
    for q in balanced_qs:
        errs = validator.validate_question(q)
        if errs:
            all_errors.extend(errs)

    if all_errors:
        print(f"Validation failed with {len(all_errors)} errors:")
        for err in all_errors[:10]:
            print(f"  - {err}")
        raise ValueError("Content Validation failed!")

    out_file = "data/questions/polity/parliamentary_committees_grand_test.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(balanced_qs, f, ensure_ascii=False, indent=2)

    print(f"Successfully wrote {len(balanced_qs)} Grand Test MCQs to {out_file}")

if __name__ == "__main__":
    main()
