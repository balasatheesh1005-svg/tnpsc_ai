CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    meta_username TEXT;
    meta_full_name TEXT;
    meta_mobile TEXT;
    user_email TEXT;
BEGIN
    meta_username :=
        NULLIF(
            pg_catalog.btrim(new.raw_user_meta_data->>'username'),
            ''
        );

    meta_full_name :=
        NULLIF(
            pg_catalog.btrim(new.raw_user_meta_data->>'full_name'),
            ''
        );

    meta_mobile :=
        NULLIF(
            pg_catalog.btrim(new.raw_user_meta_data->>'mobile_number'),
            ''
        );

    user_email :=
        NULLIF(
            pg_catalog.btrim(new.email),
            ''
        );

    IF meta_username IS NULL THEN
        RAISE EXCEPTION
            'Profile creation failed: Username metadata is required.';
    END IF;

    IF user_email IS NULL THEN
        RAISE EXCEPTION
            'Profile creation failed: Email is required.';
    END IF;

    INSERT INTO public.profiles (
        id,
        username,
        email,
        full_name,
        mobile_number
    )
    VALUES (
        new.id,
        meta_username,
        user_email,
        meta_full_name,
        meta_mobile
    );

    RETURN new;
END;
$function$
;
REVOKE ALL ON FUNCTION public."handle_new_user"() FROM PUBLIC, anon, authenticated;
CREATE OR REPLACE FUNCTION public.get_global_leaderboard()
 RETURNS TABLE(username text, accuracy numeric)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
    SELECT
        up.username,
        ROUND(AVG(up.accuracy)::numeric, 2) AS accuracy
    FROM public.users_progress AS up
    WHERE auth.uid() IS NOT NULL AND up.username IS NOT NULL
      AND up.username <> ''
    GROUP BY up.username
    ORDER BY accuracy DESC
    LIMIT 10;
$function$
;
